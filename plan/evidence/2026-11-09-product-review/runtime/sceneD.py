from d import *
K = ("base","mood","when","moment","sign","reason","screen")
def pres(sig): return dev(dev="presence", signal=sig)
mark("D1 lock, unlock after 20 s")
pres("locked"); sl(5); bstate(*K)
adv(s=20); pres("unlocked"); sl(6); bstate(*K)
mark("D2 lock again within the hour, unlock after 3 min")
pres("locked"); sl(5); adv(m=3); pres("unlocked"); sl(6)
mark("D3 away 15 min by idle time (no lock), then back")
dev(dev="presence", idle_ms=0)
adv(m=11); dev(dev="presence", idle_ms=11*60000); sl(2); adv(s=10); sl(2); bstate(*K)
adv(m=4); dev(dev="presence", idle_ms=0); sl(1); adv(s=5); sl(7); bstate(*K)
mark("D4 lock at night (after 22:00)")
adv(m=20); sl(1)
pres("locked"); sl(7); bstate(*K)
mark("D5 the night passes (30 min steps to 07:40)")
for i in range(18):
    adv(m=30); sl(0.6)
bstate(*K)
adv(m=30); sl(1); bstate(*K)
mark("D6 morning: unlock")
pres("unlocked"); sl(1); dev(dev="presence", idle_ms=0); sl(12); bstate(*K)
sl(8); bstate(*K)
mark("D7 end")
