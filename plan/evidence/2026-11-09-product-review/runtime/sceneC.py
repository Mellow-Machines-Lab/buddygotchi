from d import *
c1 = Agent("rv-c1", "/tmp/rv/api")
c2 = Agent("rv-c2", "/tmp/rv/web")
c3 = Agent("rv-c3", "/tmp/rv/infra", agent="codex")
K = ("base","act","busy","idle","helpers","when","todo","moment","wact","calls","call")
mark("C1 three agents start")
for c in (c1, c2, c3):
    c.start(); sl(0.3)
c1.prompt("fix the nav bug and add tests"); sl(1.2)
c2.prompt("review the settings page in parallel"); sl(1.2)
c3.prompt("bump the terraform provider"); sl(1.2)
bstate(*K)
mark("C2 todo + helper out")
c1.call("TodoWrite", {"todos": [{"content": "a", "status": "completed", "activeForm": "a"}, {"content": "b", "status": "in_progress", "activeForm": "b"}, {"content": "c", "status": "pending", "activeForm": "c"}]}); sl(0.5)
c2.pre("Task", {"description": "review settings", "prompt": "review", "subagent_type": "Explore"}); sl(0.2)
c2.h("SubagentStart", agent_id="h1", agent_type="Explore"); sl(0.5)
c2.call("Read", {"file_path": "/tmp/rv/web/settings.tsx"}, agent_id="h1", agent_type="Explore"); sl(0.5)
c3.call("shell", {"command": ["bash", "-lc", "terraform plan"]}); sl(1.5)
bstate(*K)
mark("C3 helper returns")
c2.h("SubagentStop", agent_id="h1", agent_type="Explore", last_assistant_message="Looks fine."); sl(0.3)
c2.post({"content": "report"}); sl(4)
bstate(*K)
mark("C4 long turn: tiers")
for label, secs in (("35s", 35), ("1min", 30), ("2min", 60), ("5min", 185), ("10min", 300), ("16min", 360)):
    adv(s=secs); sl(0.4)
    c1.read("/tmp/rv/api/nav.ts"); c2.read("/tmp/rv/web/a.ts"); c3.call("shell", {"command": ["bash", "-lc", "ls"]})
    sl(3.5)
    print(label); bstate("when","moment","act","todo")
mark("C5 push after >30 min: full work act")
adv(m=20); sl(1)
c1.pre("Bash", {"command": "git push origin fix-nav"}); sl(6)
bstate(*K)
c1.post({"stdout": "ok"}); sl(6)
bstate(*K)
mark("C6 finishes: three in a row")
c1.stop("Fixed the nav bug, added tests, pushed."); sl(1)
c2.stop("Reviewed the settings page: two small issues."); sl(1)
c3.h("Stop", last_assistant_message="Bumped the provider.")
sl(14)
bstate(*K)
mark("C7 end")
