#!/usr/bin/env node
// Design JSON is the source. Generated shipping files never import internal code.
import fs from 'node:fs';
import {firmwareCatalog} from './catalog.mjs';
import {artCatalog} from './art.mjs';
import {meshCatalog} from './mesh.mjs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../../..');
const g=JSON.parse(fs.readFileSync(path.join(root,'characters/boop/design/slime-blob/emotion-graph.json')));
if(process.argv.includes('--help')) {console.log('node characters/boop/tools/slimegen/slimegen.mjs [--check]\nGenerate the host graph, offline Mac mirror and native gel catalogs from the slime catalog.');process.exit(0);}
// The host graph goes into Boop's character pack (characters/CHARACTER.md
// §4-5): its `moods` and `pacing`. Other keys, and keys a mood has that the
// design doesn't set (`quiet_never`, `face`), are kept as they are. A mood's
// `moves` are the pack's own: the design's edges are what the gel draws a
// transition for, and they seed a mood the pack doesn't have yet. The
// design's pixel `fallback` stays in the design: a pack has every mood.
const characterPath='characters/boop/character.json';
const character=JSON.parse(fs.readFileSync(path.join(root,characterPath)));
const owned=['id','meaning','family','brief'];
const before=new Map((character.moods||[]).map(m=>[m.id,m]));
character.pacing={ordinary_dwell_ms:g.hostPolicy.ordinaryDwellMs,reverse_cooldown_ms:g.hostPolicy.reverseCooldownMs,brief_exit_ms:g.hostPolicy.briefExitMs,fresh_evidence_ms:g.hostPolicy.freshEvidenceMs};
character.moods=Object.entries(g.nodes).map(([id,n])=>({id,meaning:n.meaning,family:n.family,brief:n.brief,moves:{ordinary:n.ordinary,dramatic:n.dramatic},
  ...Object.fromEntries(Object.entries(before.get(id)||{}).filter(([k])=>!owned.includes(k)))}));
const outputs = new Map([[characterPath,JSON.stringify(character,null,2)+'\n'],['characters/boop/firmware/include/slime.h',firmwareCatalog(root)]]);
const design=path.join(root,'characters/boop/design/slime-blob');
const catalog=JSON.parse(fs.readFileSync(path.join(design,'expressions.json')));
outputs.set('characters/boop/firmware/include/slime_art.h',artCatalog(catalog.expressions));
outputs.set('characters/boop/firmware/include/slime_mesh.h',meshCatalog());
const bundled=require(path.join(design,'tools/bundle.cjs')).bundle(path.join(root,'characters/boop/tools/slimegen/mirror.mjs'));
outputs.set('characters/boop/mac/mirror/slime.js','// Generated by characters/boop/tools/slimegen/slimegen.mjs. Do not edit.\nwindow.SlimeCatalog='+JSON.stringify({...catalog,graph:g})+';\n'+bundled.replace(/^.*\n/,''));
for(const [source,target] of [['mirror.html','index.html'],['mirror.css','slime.css']]) outputs.set('characters/boop/mac/mirror/'+target,fs.readFileSync(path.join(root,'characters/boop/tools/slimegen',source),'utf8'));
for(const [name,content] of outputs) {
  const target=path.join(root,name);
  if(process.argv.includes('--check')) {if(fs.readFileSync(target,'utf8')!==content)throw Error('Stale '+name);}
  else {fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content);}
}
console.log((process.argv.includes('--check')?'SLIMEGEN PASS: fresh':'Generated')+' host graph, Mac mirror and native gel ('+outputs.size+' files)');
