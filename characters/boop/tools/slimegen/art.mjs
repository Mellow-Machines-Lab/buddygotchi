// Captures the face painter's art as compact vector paths. This keeps every
// authored silhouette; the firmware moves and sizes the eyes and mouth by its
// controls. No frames or rendering are sent across the device link.
import {paintArt} from './painter.mjs';
import {faceTarget} from './face.mjs';
const identity=()=>[1,0,0,1,0,0];
const mul=(a,b)=>[a[0]*b[0]+a[2]*b[1],a[1]*b[0]+a[3]*b[1],a[0]*b[2]+a[2]*b[3],a[1]*b[2]+a[3]*b[3],a[0]*b[4]+a[2]*b[5]+a[4],a[1]*b[4]+a[3]*b[5]+a[5]];
function color(value){
 if(typeof value==='object')value=value.color;
 if(value.startsWith('#'))return [...[1,3,5].map(at=>parseInt(value.slice(at,at+2),16)),1];
 const a=value.match(/[\d.]+/g).map(Number);return [...a.slice(0,3),a[3]??1];
}
class Capture {
 constructor(profile){this.profile=profile;this.m=identity();this.globalAlpha=1;this.fillStyle='#000000';this.strokeStyle='#000000';this.lineWidth=1;this.stack=[];this.paths=[];this.group=0;this.clipPath=[];this.path=[];}
 point(x,y){const m=this.m;return [(m[0]*x+m[2]*y+m[4]-256)/317.44,(256-m[1]*x-m[3]*y-m[5])/317.44];}
 setTransform(...m){this.m=m;}clearRect(){}
 save(){this.stack.push({m:[...this.m],globalAlpha:this.globalAlpha,fillStyle:this.fillStyle,strokeStyle:this.strokeStyle,lineWidth:this.lineWidth,group:this.group,clipPath:this.clipPath});}
 restore(){Object.assign(this,this.stack.pop());}
 scale(x,y){this.m=mul(this.m,[x,0,0,y,0,0]);}
 rotate(t){this.m=mul(this.m,[Math.cos(t),Math.sin(t),-Math.sin(t),Math.cos(t),0,0]);}
 translate(x,y){const a=this.profile.art;if(y===a.eyeY&&Math.abs(x)===a.eyeX)this.group=x<0?1:2;else if(x===0&&y===a.mouthY)this.group=3;this.m=mul(this.m,[1,0,0,1,x,y]);}
 beginPath(){this.path=[];this.current=[];}
 moveTo(x,y){this.current=[this.point(x,y)];this.path.push(this.current);}
 lineTo(x,y){this.current.push(this.point(x,y));}
 quadraticCurveTo(x,y,u,v){const p=this.current.at(-1),b=this.point(x,y),c=this.point(u,v);for(let i=1;i<=12;i++){const t=i/12,k=1-t;this.current.push([k*k*p[0]+2*k*t*b[0]+t*t*c[0],k*k*p[1]+2*k*t*b[1]+t*t*c[1]]);}}
 bezierCurveTo(x,y,u,v,a,b){const p=this.current.at(-1),c=this.point(x,y),d=this.point(u,v),e=this.point(a,b);for(let i=1;i<=18;i++){const t=i/18,k=1-t;this.current.push([k**3*p[0]+3*k*k*t*c[0]+3*k*t*t*d[0]+t**3*e[0],k**3*p[1]+3*k*k*t*c[1]+3*k*t*t*d[1]+t**3*e[1]]);}}
 ellipse(x,y,rx,ry,angle){const points=[];for(let i=0;i<=40;i++){const t=i/40*Math.PI*2,u=Math.cos(t)*rx,v=Math.sin(t)*ry;points.push(this.point(x+u*Math.cos(angle)-v*Math.sin(angle),y+u*Math.sin(angle)+v*Math.cos(angle)));}this.current=points;this.path.push(points);}
 closePath(){if(this.current?.length)this.current.push([...this.current[0]]);}
 clip(){this.clipPath=this.path.flat();}
 createLinearGradient(){return {color:'rgba(117,201,235,.41)',addColorStop(){}};}
 fill(){this.record(false);}stroke(){this.record(true);}
 record(stroke){const rgba=color(stroke?this.strokeStyle:this.fillStyle);rgba[3]*=this.globalAlpha;let group=this.group;
  if(!group)group=rgba[2]>rgba[0]&&rgba[1]>150?4:5;
  const width=stroke?this.lineWidth*Math.hypot(this.m[0],this.m[1])/317.44:0;
  for(const points of this.path)if(points.length>1)this.paths.push({points,clip:this.clipPath,rgba,width,group});
 }
}
export function artCatalog(profiles){
 const vertices=[],paths=[],ranges=[],shapes=[1,2,3,4,5].map(()=>[]);const point=p=>p.map(x=>Math.round(x*4096));
 for(const [id,profile] of Object.entries(profiles)){
  const ctx=new Capture(profile);
  paintArt(ctx,profile,faceTarget(profile));const first=paths.length;
  for(const p of ctx.paths){const at=vertices.length;vertices.push(...p.points.map(point));const clip=vertices.length;vertices.push(...p.clip.map(point));const [r,g,b,alpha]=p.rgba;paths.push([at,p.points.length,clip,p.clip.length,Math.round(p.width*4096),p.group,Math.round(alpha*255),(r>>3)<<11|(g>>2)<<5|b>>3]);}
  // Each group's shape: its paths' point counts, fill or stroke and colour,
  // so two arts of one shape morph, path by path and point by point.
  const own=paths.slice(first),shape=shapes.map((known,g)=>{
   const key=own.filter(p=>p[5]===g+1).map(p=>[p[1],p[3],p[4]>0,p[7]].join('/')).join(' ');
   if(!known.includes(key))known.push(key);return known.indexOf(key);});
  ranges.push([first,paths.length-first,'{'+shape.join(',')+'}']);
 }
 let out='// Generated by slimegen from the original face painter. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace slime {\nstruct ArtPoint {int16_t x,y;};\nstruct ArtPath {uint32_t first;uint16_t count;uint32_t clip;uint16_t clipCount,width;uint8_t group,alpha;uint16_t color;};\n// shape: each group\'s (1 to 5), the same number exactly when two arts\' paths there pair up.\nstruct ArtRange {uint16_t first,count;uint8_t shape[5];};\n';
 for(const [type,name,values] of [['ArtPoint','kArtPoints',vertices],['ArtPath','kArtPaths',paths],['ArtRange','kArt',ranges]])out+='inline constexpr '+type+' '+name+'[]={\n'+values.map(v=>'{'+v.join(',')+'}').join(',\n')+'\n};\n';
 return out+'}\n';
}
