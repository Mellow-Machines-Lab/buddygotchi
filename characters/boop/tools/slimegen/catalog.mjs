// Firmware catalog emitter. No runtime import from internal/ is shipped.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {faceTarget} from './face.mjs';
import {profileTraits,sceneMoodTraits,gestureGagName,gestureGag,gestureNames,noticeNames,idleOccasions,occasionGags,occasionShare} from './scenes.mjs';
import {recipes,kinds} from './recipes.mjs';
const require=createRequire(import.meta.url);
// The acting springs a cue or a gag's key names: the six gestures', then a
// gag's own slide and lids (keys only).
const channels=['lean','squash','ripple','lift','roll','forward','slide','lids'];
const controls=['eyeX','eyeY','eyeOpen','mouthY','mouthWidth','curve','cheekAlpha','tearAmount'];
const t=n=>'T::literal('+n+')';
const q=n=>'F::fromRaw('+Math.round(n*16777216)+')',s=JSON.stringify;
// A cue or a key: when, which channel, and its velocity or value.
const onChannel=([at,c,v])=>'{'+t(at)+','+channels.indexOf(c)+','+q(v)+'}';
const enumName=name=>name.split(/[^a-z0-9]/i).map(part=>part[0].toUpperCase()+part.slice(1)).join('');
export function firmwareCatalog(root){
 const base=path.join(root,'characters/boop/design/slime-blob');
 const read=name=>JSON.parse(fs.readFileSync(path.join(base,name)));
 const design=read('expressions.json'),profiles=design.expressions,graph=read('emotion-graph.json'),sound=read('sound/sound-plan.json');
 // The notice state plays the pack's rig clip, which its recipe times.
 design.noticeClip=JSON.parse(fs.readFileSync(path.join(root,'characters/boop/rig/clips/notice.json')));
 // Every gag the port plays: comedy's, then each gesture's, then the
 // occasions' (each once).
 const allGags=[...Object.entries(design.gags),...design.gestures.map(g=>[gestureGagName(g),gestureGag(g)]),...occasionGags(design.occasions)];
 const ids=Object.keys(profiles),index=id=>ids.indexOf(id),gagIds=allGags.map(([id])=>id);
 // A tag's bit, in render::kTagNames' order (firmware/src/render/tags.h).
 const tagNames=[...fs.readFileSync(path.join(root,'firmware/src/render/tags.h'),'utf8').match(/kTagNames\[kTagCount\] = \{([\s\S]*?)\};/)[1].matchAll(/"(\w+)"/g)].map(m=>m[1]);
 const tagBits=when=>when.reduce((bits,tag)=>{if(!tagNames.includes(tag))throw Error('unknown tag '+tag+': tags.h has '+tagNames);return bits|2**tagNames.indexOf(tag);},0);
 const ownGags=Math.max(...Object.values(profiles).map(p=>(p.gags||[]).length));
 let out='// Generated by characters/boop/tools/slimegen/slimegen.mjs. Do not edit.\n#pragma once\n#include <cstdint>\n#include "render/gel/time.h"\nnamespace slime {\nusing render::gel::F;using render::gel::T;\n';
 out+='constexpr int kProfiles='+ids.length+', kCanonical='+Object.keys(graph.nodes).length+';\n';
 out+=ids.map((id,i)=>'constexpr int k'+enumName(id)+'='+i+';').join('\n')+'\n';
 const performance=perf=>'{'+s(perf.type)+','+t(perf.duration)+','+perf.cues.length+', {'+perf.cues.map(onChannel).join(',')+'}}';
 // A gag is a performance (its impulses) with keyed targets and contacts
 // that sound; idle deals a mood's own gags, then everyone's idle gags.
 out+='struct GestureCue {T at;uint8_t channel;F velocity;};\nstruct Performance {const char* type;T duration;uint8_t count;GestureCue cues[7];};\n';
 out+='struct GagKey {T at;uint8_t channel;F value;};\nstruct GagContact {T at;uint8_t kind;F strength;};\n';
 out+='struct Gag {Performance gesture;uint8_t keyCount;GagKey keys[24];uint8_t contactCount;GagContact contacts[4];};\n';
 out+='constexpr int kOwnGags='+ownGags+';\n';
 out+='struct Profile {const char* id;uint8_t canonical;const char* eyes;const char* mouth;const char* cheeks;const char* tears;F face[8];F traits[4];bool representative;Performance performances[3];F pitch,gain;uint8_t gagCount;uint8_t gags[kOwnGags];};\n';
 out+='constexpr Gag kGags[]={\n';
 for(const [id,gag] of allGags){
  out+='{'+[performance({...gag,type:id}),gag.keys.length,'{'+gag.keys.map(onChannel).join(',')+'}',
   gag.contacts.length,'{'+gag.contacts.map(([at,kind,strength])=>'{'+t(at)+','+kinds.indexOf(kind)+','+q(strength)+'}').join(',')+'}'].join(',')+'},\n';
 }
 out+='};\nconstexpr int kGagCount=sizeof(kGags)/sizeof(kGags[0]);\n';
 out+='constexpr uint8_t kIdleGags[]={'+design.idleGags.map(id=>gagIds.indexOf(id)).join(',')+'};\nconstexpr int kIdleGagCount=sizeof(kIdleGags);\n';
 out+='constexpr int kMaxGestures=3+kOwnGags+kIdleGagCount;\n';
 // A gesture's face, the expression the board borrows while it plays, in
 // render::Gesture's order; idle's occasions: their tags (bits), wait
 // (seconds) and gag; and how often a pick goes to one that fits.
 if(JSON.stringify(design.gestures.map(g=>g.id))!==JSON.stringify(gestureNames))throw Error('gestures out of render::Gesture order');
 out+='constexpr int kGestureCount='+design.gestures.length+';\nconstexpr int8_t kGestureFaces[kGestureCount]={'+design.gestures.map(g=>index(g.face)).join(',')+'};\n';
 // The notice state's takes' faces, which the board borrows the same way.
 if(JSON.stringify(design.notices.map(g=>g.id))!==JSON.stringify(noticeNames))throw Error('notices out of order');
 out+='constexpr int kNoticeCount='+design.notices.length+';\nconstexpr int8_t kNoticeFaces[kNoticeCount]={'+design.notices.map(g=>index(g.face)).join(',')+'};\n';
 out+='struct IdleOccasion {uint32_t when;uint16_t after;uint8_t gag;};\nconstexpr IdleOccasion kIdleOccasions[]={\n'+
  idleOccasions(design.occasions).map(o=>'{'+[tagBits(o.when),o.after,gagIds.indexOf(o.gag)].join(',')+'},').join('\n')+'\n};\n';
 out+='constexpr int kIdleOccasionCount=sizeof(kIdleOccasions)/sizeof(kIdleOccasions[0]);\nconstexpr F kOccasionShare='+q(occasionShare)+';\n';
 out+='constexpr Profile kProfile[kProfiles]={\n';
 for(const [id,p] of Object.entries(profiles)){
  const f=faceTarget(p),traits=profileTraits(p),sp=sound.moodProfiles[p.mood],own=p.gags||[];
  out+='{'+[s(id),index(p.mood),s(p.art.eyes),s(p.art.mouth),s(p.art.cheeks),s(p.tears),'{'+controls.map(k=>q(f[k])).join(',')+'}','{'+['delayMs','spacing','gain','lean'].map(k=>q(traits[k])).join(',')+'}',Boolean(sceneMoodTraits[p.mood]),'{'+p.performances.map(performance).join(',')+'}',q(sp.pitch),q(sp.gain),
   own.length,'{'+own.map(gag=>gagIds.indexOf(gag)).join(',')+'}'].join(',')+'},\n';
 }
 out+='};\nstruct Edge {uint8_t from,to;bool dramatic;};\nconstexpr Edge kEdges[]={\n';
 for(const [from,node] of Object.entries(graph.nodes))for(const category of ['ordinary','dramatic'])for(const to of node[category])out+='{'+index(from)+','+index(to)+','+(category==='dramatic')+'},\n';
 out+='};\nconstexpr int kEdgeCount=sizeof(kEdges)/sizeof(kEdges[0]);\n';
 out+='constexpr F kRoutineProbability='+q(sound.mix.routineContactProbability)+';\nconstexpr int kMaxRoutine='+sound.mix.maxRoutineGesturesPerCycle+', kShortLoopMs='+sound.mix.shortLoopMinimumSeconds*1000+', kShortLoopEvery='+sound.mix.shortLoopSoundEvery+';\n';
 out+='constexpr F kPitchLo='+q(sound.seededVariation.pitch[0])+', kPitchHi='+q(sound.seededVariation.pitch[1])+', kGainLo='+q(sound.seededVariation.gain[0])+', kGainHi='+q(sound.seededVariation.gain[1])+';\n';
 out+=recipes(profiles,q,t,{design,gagIds,tagBits});
 const sfx=require(path.join(base,'sound/sfx.js')),samples=[],clips=[];
 for(const name of Object.keys(sfx.recipes))for(let variant=0;variant<3;variant++){
  const clip=sfx.render(name,{sampleRate:11025,seed:53,variant,pitch:1,gain:.8});
  clips.push({name:name+'-'+variant,at:samples.length,len:clip.data.length});
  for(const value of clip.data)samples.push(Math.max(0,Math.min(255,Math.round(128+127*value/.8))));
 }
 out+='constexpr int kRate=11025;\nstruct Clip {const char* name;uint32_t at,len;};\nconstexpr Clip kClip[]={\n'+clips.map(c=>'{'+s(c.name)+','+c.at+','+c.len+'}').join(',\n')+'\n};\nconstexpr int kClipCount=sizeof(kClip)/sizeof(kClip[0]);\nconstexpr uint8_t kSamples[]={\n';
 for(let i=0;i<samples.length;i+=32)out+=samples.slice(i,i+32).join(',')+',\n';
 out+='};\nconstexpr uint32_t kSampleBytes=sizeof(kSamples);\n}\n';
 return out.replaceAll('constexpr ','inline constexpr ');
}
