// Firmware catalog emitter. No runtime import from internal/ is shipped.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {faceTarget} from '../../design/slime-blob/engine/face.mjs';
import {profileTraits} from '../../design/slime-blob/engine/scenes/profile.mjs';
import {sceneMoodTraits} from '../../design/slime-blob/engine/scenes/mood.mjs';
import {recipes} from './recipes.mjs';
const require=createRequire(import.meta.url);
const channels=['lean','squash','ripple','lift','roll','forward'];
const controls=['eyeX','eyeY','eyeOpen','mouthY','mouthWidth','curve','cheekAlpha','tearAmount'];
const t=n=>'T::literal('+n+')';
const q=n=>'F::fromRaw('+Math.round(n*16777216)+')',s=JSON.stringify;
const enumName=name=>name.split(/[^a-z0-9]/i).map(part=>part[0].toUpperCase()+part.slice(1)).join('');
export function firmwareCatalog(root){
 const base=path.join(root,'characters/boop/design/slime-blob');
 const read=name=>JSON.parse(fs.readFileSync(path.join(base,name)));
 const profiles=read('expressions.json').expressions,graph=read('emotion-graph.json'),sound=read('sound/sound-plan.json');
 const ids=Object.keys(profiles),index=id=>ids.indexOf(id);
 let out='// Generated by characters/boop/tools/slimegen/slimegen.mjs. Do not edit.\n#pragma once\n#include <cstdint>\n#include "render/gel/time.h"\nnamespace slime {\nusing render::gel::F;using render::gel::T;\n';
 out+='constexpr int kProfiles='+ids.length+', kCanonical='+Object.keys(graph.nodes).length+';\n';
 out+=ids.map((id,i)=>'constexpr int k'+enumName(id)+'='+i+';').join('\n')+'\n';
 out+='struct GestureCue {T at;uint8_t channel;F velocity;};\nstruct Performance {const char* type;T duration;uint8_t count;GestureCue cues[7];};\nstruct Profile {const char* id;uint8_t canonical;const char* eyes;const char* mouth;const char* cheeks;const char* tears;F face[8];F traits[4];bool representative;Performance performances[3];F pitch,gain;};\n';
 out+='constexpr Profile kProfile[kProfiles]={\n';
 for(const [id,p] of Object.entries(profiles)){
  const f=faceTarget(p),traits=profileTraits(p),sp=sound.moodProfiles[p.mood];
  const perfs=p.performances.map(perf=>'{'+s(perf.type)+','+t(perf.duration)+','+perf.cues.length+', {'+perf.cues.map(([at,c,v])=>'{'+t(at)+','+channels.indexOf(c)+','+q(v)+'}').join(',')+'}}');
  out+='{'+[s(id),index(p.mood),s(p.art.eyes),s(p.art.mouth),s(p.art.cheeks),s(p.tears),'{'+controls.map(k=>q(f[k])).join(',')+'}','{'+['delayMs','spacing','gain','lean'].map(k=>q(traits[k])).join(',')+'}',Boolean(sceneMoodTraits[p.mood]),'{'+perfs.join(',')+'}',q(sp.pitch),q(sp.gain)].join(',')+'},\n';
 }
 out+='};\nstruct Edge {uint8_t from,to;bool dramatic;};\nconstexpr Edge kEdges[]={\n';
 for(const [from,node] of Object.entries(graph.nodes))for(const category of ['ordinary','dramatic'])for(const to of node[category])out+='{'+index(from)+','+index(to)+','+(category==='dramatic')+'},\n';
 out+='};\nconstexpr int kEdgeCount=sizeof(kEdges)/sizeof(kEdges[0]);\n';
 out+='constexpr F kRoutineProbability='+q(sound.mix.routineContactProbability)+';\nconstexpr int kMaxRoutine='+sound.mix.maxRoutineGesturesPerCycle+', kShortLoopMs='+sound.mix.shortLoopMinimumSeconds*1000+', kShortLoopEvery='+sound.mix.shortLoopSoundEvery+';\n';
 out+='constexpr F kPitchLo='+q(sound.seededVariation.pitch[0])+', kPitchHi='+q(sound.seededVariation.pitch[1])+', kGainLo='+q(sound.seededVariation.gain[0])+', kGainHi='+q(sound.seededVariation.gain[1])+';\n';
 out+=recipes(profiles,q,t);
 const sfx=require(path.join(base,'sound/sfx.js')),samples=[],clips=[];
 for(const name of Object.keys(sfx.recipes))for(let variant=0;variant<3;variant++){
  const clip=sfx.render(name,{sampleRate:11025,seed:53,variant,pitch:1,gain:.8});
  clips.push({name:name+'-'+variant,at:samples.length,len:clip.data.length});
  for(const value of clip.data)samples.push(Math.max(0,Math.min(255,Math.round(128+127*value/.8))));
 }
 out+='constexpr int kRate=11025;\nstruct Clip {const char* name;uint32_t at,len;};\nconstexpr Clip kClip[]={\n'+clips.map(c=>'{'+s(c.name)+','+c.at+','+c.len+'}').join(',\n')+'\n};\nconstexpr int kClipCount=sizeof(kClip)/sizeof(kClip[0]);\nconstexpr uint8_t kSamples[]={\n';
 for(let i=0;i<samples.length;i+=32)out+=samples.slice(i,i+32).join(',')+',\n';
 out+='};\nconstexpr uint32_t kSampleBytes=sizeof(kSamples);\n}\n';
 return out.replaceAll('constexpr ','inline constexpr ');
}
