// Dependency-free, deliberately small ESM-to-IIFE bundler for our named imports/exports.
// Reject unsupported module syntax instead of silently emitting a broken file:// build.
const fs=require('node:fs'),path=require('node:path');
function bundle(entry){
  const modules=new Map();
  function visit(file){
    file=path.resolve(file);if(modules.has(file))return modules.get(file).id;
    const item={id:modules.size,body:''};modules.set(file,item);
    let source=fs.readFileSync(file,'utf8');
    source=source.replace(/^import\s+\{([^}]+)\}\s+from\s+['"](.+?)['"];?\s*$/gm,(_,names,relative)=>{
      if(!relative.startsWith('.'))throw Error('Only local imports are supported: '+relative);
      const id=visit(path.resolve(path.dirname(file),relative));
      return `const {${names.replace(/\s+as\s+/g,':')}}=__load(${id});`;
    });
    const exports=[];
    source=source.replace(/^export\s+(function|const|let|class)\s+(\w+)/gm,(_,kind,name)=>{exports.push(name);return `${kind} ${name}`;});
    source=source.replace(/^export\s*\{([^}]+)\};?\s*$/gm,(_,names)=>{for(const name of names.split(','))exports.push(name.trim());return '';});
    if(/^\s*(?:import|export)\s/m.test(source))throw Error('Unsupported module syntax in '+file);
    item.body=source+`\nreturn {${exports.join(',')}};`;return item.id;
  }
  const id=visit(entry);
  return '// Generated by tools/build.cjs from engine/, render/ and preview/character.mjs. Do not edit.\n(()=>{\nconst __modules={\n'+[...modules.values()].map(m=>`${m.id}:()=>{\n${m.body}\n}`).join(',\n')+'\n};\nconst __cache={};function __load(id){return __cache[id]||(__cache[id]=__modules[id]());}\n__load('+id+');\n})();\n';
}
module.exports={bundle};
